function getProviderInitials($name) {
    $words = explode(' ', trim((string)$name));
    $initials = '';
    foreach ($words as $w) {
        if (!empty($w)) {
            $initials .= strtoupper(mb_substr($w, 0, 1));
            if (strlen($initials) >= 2) break;
        }
    }
    return $initials ?: 'SP';
}
